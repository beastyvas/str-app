const placeholders = readJSON(PLACEHOLDERS_FILE, {});
const rel = f => path.relative(path.join(ROOT, 'src/constants'), f).split(path.sep).join('/');

const rows = [];
const lines = [
  '// AUTO-GENERATED by scripts/sync-cameo-registry.mjs — do not edit.',
  '// Static require() map so Metro can bundle every cameo image.',
  "import type { CharacterId } from './cast';",
  '',
  'export interface CameoImages {',
  '  portrait: number;',
  '  /** Powered-up variant; falls back to portrait when missing */',
  '  hype: number | null;',
  '  /** Still the generated circle+initials placeholder */',
  '  placeholder: boolean;',
  '}',
  '',
  'export const CAMEO_IMAGES: Record<CharacterId, CameoImages> = {',
];
for (const c of CAST) {
  const dir = path.join(CAMEOS, c.id);
  const portrait = path.join(dir, 'portrait.png');
  const hype = path.join(dir, 'hype.png');
  if (!fs.existsSync(portrait)) {
    console.error(`Missing ${path.relative(ROOT, portrait)} — run make-cameo-placeholders.mjs first.`);
    process.exit(1);
  }
  const isPlaceholder = placeholders[c.id] === sha1(portrait);
  const hasHype = fs.existsSync(hype);
  lines.push(`  ${c.id}: { portrait: require('${rel(portrait)}'), hype: ${hasHype ? `require('${rel(hype)}')` : 'null'}, placeholder: ${isPlaceholder} },`);
  rows.push({ c, isPlaceholder, hasHype });
}
lines.push('};', '');
fs.writeFileSync(path.join(ROOT, 'src/constants/cameoRegistry.generated.ts'), lines.join('\n'));

const md = [
  '# Cast checklist',
  '',
  '_Regenerated by `node scripts/sync-cameo-registry.mjs`. Image specs: see README.md._',
  '',
];
for (const w of WORLD_ORDER) {
  const inWorld = rows.filter(r => worldOf(r.c) === w);
  if (!inWorld.length) continue;
  md.push(`## ${WORLD_NAME[w]}`, '', '| ID | Name | Portrait | Hype | Suggested shot |', '|---|---|---|---|---|');
  for (const { c, isPlaceholder, hasHype } of inWorld) {
    const name = c.role === 'lead' ? `**${c.name}** (lead)` : c.name;
    md.push(`| \`${c.id}\` | ${name} | ${isPlaceholder ? 'placeholder' : '**real**'} | ${hasHype ? '**real**' : 'missing'} | ${SUGGESTED_SHOTS[c.id] ?? ''} |`);
  }
  md.push('');
}
const real = rows.filter(r => !r.isPlaceholder).length;
md.push(`**${real} / ${rows.length}** portraits are real art · **${rows.filter(r => r.hasHype).length}** hype images.`, '');
fs.writeFileSync(path.join(CAMEOS, 'CAST_CHECKLIST.md'), md.join('\n'));
console.log(`Registry synced: ${rows.length} characters, ${real} real portraits, ${rows.filter(r => r.hasHype).length} hype.`);
